const crypto = require("crypto");
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");
const buildDir = path.join(root, "build");
const manifestPath = path.join(buildDir, "asset-manifest.json");

if (!fs.existsSync(manifestPath)) {
  throw new Error("build/asset-manifest.json is missing; run the React build first");
}

const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const compiledAssets = Object.values(manifest.files || {})
  .filter((url) => typeof url === "string" && /\.(?:css|js)$/.test(url));
const shellUrls = [...new Set([
  "/",
  "/index.html",
  "/manifest.json",
  "/favicon.ico",
  "/logo192.png",
  "/logo512.png",
  ...compiledAssets,
])];
const versionHash = crypto.createHash("sha256");
for (const url of shellUrls) {
  const relativePath = url === "/" ? "index.html" : url.replace(/^\//, "");
  const filePath = path.join(buildDir, relativePath);
  versionHash.update(url);
  if (fs.existsSync(filePath) && fs.statSync(filePath).isFile()) {
    versionHash.update(fs.readFileSync(filePath));
  }
}
const version = versionHash.digest("hex").slice(0, 12);

const worker = `// Generated by scripts/generate-service-worker.js. Do not edit build output.
const CACHE_PREFIX = "finger-training-shell-";
const CACHE_NAME = CACHE_PREFIX + "${version}";
const SHELL_URLS = ${JSON.stringify(shellUrls, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(SHELL_URLS))
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((names) => Promise.all(
        names
          .filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)
          .map((name) => caches.delete(name))
      ))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request).catch(() =>
        caches.match("/index.html").then((cached) => cached || caches.match("/"))
      )
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response && response.ok) {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        }
        return response;
      });
    })
  );
});
`;

fs.writeFileSync(path.join(buildDir, "service-worker.js"), worker);
console.log(`Generated service-worker.js with ${shellUrls.length} cached files (${version})`);
